import streamlit as st
import snowflake.connector
import pandas as pd
from langchain.agents import initialize_agent, AgentType
from langchain.tools import Tool
from langchain_community.chat_models import ChatGoogleGenerativeAI

st.set_page_config(page_title="RAG Agent + Text-to-SQL", layout="wide")
st.title("📊 RAG Agent with Snowflake Text-to-SQL Capability")

# 1. Initialize Database Connection
@st.cache_resource
def get_snowflake_conn():
    return snowflake.connector.connect(
        user=st.secrets["snowflake"]["user"],
        password=st.secrets["snowflake"]["password"],
        account=st.secrets["snowflake"]["account"],
        warehouse=st.secrets["snowflake"]["warehouse"],
        database="SNOWFLAKE_SAMPLE_DATA",
        schema="TPCH_SF1"
    )

conn = get_snowflake_conn()

# 2. Define the 3 Core Text-to-SQL Tools matching n8n logic
def tool_table_lookup(query: str = "") -> str:
    """Tool 1: Get list of all tables in the database schema."""
    cursor = conn.cursor()
    cursor.execute("""
        SELECT table_schema, table_name 
        FROM SNOWFLAKE_SAMPLE_DATA.information_schema.tables 
        WHERE table_schema = 'TPCH_SF1';
    """)
    rows = cursor.fetchall()
    cursor.close()
    return str([row[1] for row in rows])

def tool_column_lookup(table_name: str) -> str:
    """Tool 2: Get table definition to find all columns and types."""
    cursor = conn.cursor()
    clean_table = table_name.strip().strip("'").strip('"').upper()
    cursor.execute(f"""
        SELECT column_name, data_type 
        FROM SNOWFLAKE_SAMPLE_DATA.information_schema.columns 
        WHERE table_name = '{clean_table}' 
          AND table_schema = 'TPCH_SF1' 
        ORDER BY ordinal_position;
    """)
    rows = cursor.fetchall()
    cursor.close()
    return str(rows)

def tool_execute_sql(sql_query: str) -> str:
    """Tool 3: Execute query and get data in Snowflake."""
    cursor = conn.cursor()
    try:
        # Clean query strings generated by LLM
        clean_sql = sql_query.strip().strip("`").strip("sql").strip()
        cursor.execute(clean_sql)
        df = cursor.fetch_pandas_all()
        cursor.close()
        return df.to_markdown(index=False)
    except Exception as e:
        cursor.close()
        return f"SQL Error: {str(e)}"

# 3. Wrap functions in LangChain Tools
tools = [
    Tool(
        name="Snowflake_Table_Lookup",
        func=tool_table_lookup,
        description="Get list of all tables in database. USE THIS FIRST."
    ),
    Tool(
        name="Snowflake_Table_column_Lookup",
        func=tool_column_lookup,
        description="Get table definition to find all columns and types. USE BEFORE WRITING ANY QUERY."
    ),
    Tool(
        name="Snowflake_Execute_SQL",
        func=tool_execute_sql,
        description="Execute verified SQL query and get data in Snowflake. USE LAST."
    )
]

# 4. Configure Agent with Strict n8n System Prompt
system_instructions = """
You are a Snowflake SQL assistant.
CRITICAL RULES - FOLLOW STRICTLY:
1. Make sure you check table name and column names first.
2. You do NOT know the database schema.
3. You MUST use Snowflake_Table_Lookup FIRST to see available tables.
4. You MUST use Snowflake_Table_column_Lookup to check columns before writing ANY query.
5. NEVER assume table or column names exist.
6. ONLY after confirming schema, use Snowflake_Execute_SQL.
7. Always return the query results formatted as clean Markdown tables.
"""

llm = ChatGoogleGenerativeAI(model="gemini-1.5-pro", temperature=0)

agent = initialize_agent(
    tools=tools,
    llm=llm,
    agent=AgentType.ZERO_SHOT_REACT_DESCRIPTION,
    verbose=True,
    agent_kwargs={"prefix": system_instructions}
)

# 5. Streamlit Interactive Interface
if "messages" not in st.session_state:
    st.session_state.messages = []

for msg in st.session_state.messages:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])

if prompt := st.chat_input("Ask a question about database records:"):
    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)

    with st.chat_message("assistant"):
        with st.spinner("Analyzing schema and executing query..."):
            response = agent.run(prompt)
            st.markdown(response)
            st.session_state.messages.append({"role": "assistant", "content": response})
